/// Health Insights: analytics over the user's analysis history with animated
/// 3D charts, streaks and a shareable summary.
class HealthInsightsScreen extends StatefulWidget {
  const HealthInsightsScreen({super.key});

  @override
  State<HealthInsightsScreen> createState() => _HealthInsightsScreenState();
}

class _HealthInsightsScreenState extends State<HealthInsightsScreen> {
  final _service = AnalysisHistoryApiService();
  late Future<List<ApiAnalysisHistoryItem>> _future;

  @override
  void initState() {
    super.initState();
    _future = _service.getHistory();
  }

  Future<void> _refresh() async {
    final f = _service.getHistory();
    setState(() => _future = f);
    await f;
  }

  Future<void> _shareSummary(List<ApiAnalysisHistoryItem> items) async {
    final buffer = StringBuffer('# Care Pathway AI — Health Summary\n\n');
    buffer
      ..writeln('Total analyses: ${items.length}')
      ..writeln(
        'Average risk score: ${(items.map((e) => e.riskScore).fold<int>(0, (a, b) => a + b) / items.length).round()}/100',
      )
      ..writeln()
      ..writeln('## Recent checks')
      ..writeln();
    for (final item in items.take(10)) {
      final d = item.createdAt.toLocal();
      buffer.writeln(
        '- ${d.year}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}: '
        'risk ${item.riskScore}/100 — ${item.triageLevel} — "${_oneLine(item.symptoms)}"',
      );
    }
    buffer
      ..writeln()
      ..writeln('Generated by Care Pathway AI. Not a medical diagnosis.');

    await Share.share(
      buffer.toString(),
      subject: 'My health summary',
    );
  }

  String _oneLine(String s) =>
      s.replaceAll('\n', ' ').length > 80
          ? '${s.replaceAll('\n', ' ').substring(0, 77)}…'
          : s.replaceAll('\n', ' ');

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: context.screenBg,
      appBar: AppBar(title: const Text('Health Insights')),
      body: FutureBuilder<List<ApiAnalysisHistoryItem>>(
        future: _future,
        builder: (context, snapshot) {
          if (snapshot.connectionState == ConnectionState.waiting) {
            return Center(
              child: SizedBox(
                width: 28,
                height: 28,
                child: CircularProgressIndicator(
                  strokeWidth: 2.6,
                  color: context.primary,
                ),
              ),
            );
          }
          if (snapshot.hasError) {
            return AppEmptyState(
              icon: Icons.cloud_off_rounded,
              title: 'Could not load insights',
              message: 'Check your connection and try again.',
              action: AppButton(
                label: 'Retry',
                icon: Icons.refresh_rounded,
                variant: AppButtonVariant.outline,
                minHeight: 46,
                onPressed: _refresh,
              ),
            );
          }
          final items = snapshot.data ?? [];
          if (items.isEmpty) {
            return const AppEmptyState(
              icon: Icons.insights_rounded,
              title: 'No data yet',
              message:
                  'Complete a symptom check and your health trends will appear here.',
            );
          }
          return _InsightsBody(
            items: items,
            onShare: () => _shareSummary(items),
          );
        },
      ),
    );
  }
}

class _InsightsBody extends StatefulWidget {
  final List<ApiAnalysisHistoryItem> items;
  final VoidCallback onShare;

  const _InsightsBody({required this.items, required this.onShare});

  @override
  State<_InsightsBody> createState() => _InsightsBodyState();
}

class _InsightsBodyState extends State<_InsightsBody>
    with SingleTickerProviderStateMixin {
  late final AnimationController _grow = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 900),
    value: 0,
  );

  @override
  void initState() {
    super.initState();
    Future.delayed(const Duration(milliseconds: 250), () {
      if (mounted) _grow.forward();
    });
  }

  @override
  void dispose() {
    _grow.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final items = widget.items;
    final avgRisk =
        items.map((e) => e.riskScore).fold<int>(0, (a, b) => a + b) /
            items.length;
    final highRisk = items
        .where((e) =>
            appRiskLevelFor(e.triageLevel, e.riskScore) ==
            AppRiskLevel.emergency)
        .length;
    final streak = _computeStreak(items);

    return Center(
      child: ConstrainedBox(
        constraints:
            const BoxConstraints(maxWidth: AppDimensions.maxContentWidth),
        child: ListView(
          padding: const EdgeInsets.fromLTRB(16, 12, 16, 32),
          physics: const BouncingScrollPhysics(),
          children: [
            Row(
              children: [
                _StatTile(
                  icon: Icons.fact_check_rounded,
                  color: context.primary,
                  value: '${items.length}',
                  label: 'Total checks',
                ),
                const SizedBox(width: 10),
                _StatTile(
                  icon: Icons.speed_rounded,
                  color: AppColors.warning,
                  value: '${avgRisk.round()}',
                  label: 'Avg risk',
                ),
              ],
            ),
            const SizedBox(height: 10),
            Row(
              children: [
                _StatTile(
                  icon: Icons.sos_rounded,
                  color: AppColors.danger,
                  value: '$highRisk',
                  label: 'High-risk alerts',
                ),
                const SizedBox(width: 10),
                _StatTile(
                  icon: Icons.local_fire_department_rounded,
                  color: AppColors.urgent,
                  value: '$streak',
                  label: 'Day streak',
                ),
              ],
            ),
            const SizedBox(height: 20),
            Tilt3DCard(
              padding: const EdgeInsets.fromLTRB(16, 18, 16, 12),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    'Risk score timeline',
                    style: TextStyle(
                      color: context.textMain,
                      fontWeight: FontWeight.w700,
                      fontSize: 16,
                    ),
                  ),
                  const SizedBox(height: 4),
                  Text(
                    'Last ${items.take(14).length} checks (lower is better)',
                    style: TextStyle(color: context.textMuted, fontSize: 12.5),
                  ),
                  const SizedBox(height: 12),
                  SizedBox(
                    height: 170,
                    child: AnimatedBuilder(
                      animation: _grow,
                      builder: (context, _) => CustomPaint(
                        painter: _Bars3DPainter(
                          items: items.take(14).toList(),
                          progress: Curves.easeOutCubic.transform(_grow.value),
                          dark: context.isDarkMode,
                          muted: context.surfaceMuted,
                        ),
                      ),
                    ),
                  ),
                ],
              ),
            ),
            const SizedBox(height: 14),
            Tilt3DCard(
              padding: const EdgeInsets.all(16),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    'Triage distribution',
                    style: TextStyle(
                      color: context.textMain,
                      fontWeight: FontWeight.w700,
                      fontSize: 16,
                    ),
                  ),
                  const SizedBox(height: 14),
                  SizedBox(
                    height: 150,
                    child: AnimatedBuilder(
                      animation: _grow,
                      builder: (context, _) {
                        final counts = _countLevels(items);
                        return CustomPaint(
                          painter: _Donut3DPainter(
                            counts: counts,
                            progress: _grow.value,
                            dark: context.isDarkMode,
                          ),
                          child: Center(
                            child: Column(
                              mainAxisSize: MainAxisSize.min,
                              children: [
                                Text(
                                  '${items.length}',
                                  style: TextStyle(
                                    color: context.textMain,
                                    fontWeight: FontWeight.w800,
                                    fontSize: 24,
                                    height: 1,
                                  ),
                                ),
                                Text(
                                  'checks',
                                  style: TextStyle(
                                    color: context.textMuted,
                                    fontSize: 11.5,
                                  ),
                                ),
                              ],
                            ),
                          ),
                        );
                      },
                    ),
                  ),
                  const SizedBox(height: 10),
                  _legend(context, counts: _countLevels(items)),
                ],
              ),
            ),
            const SizedBox(height: 18),
            AppButton(
              label: 'Share my health summary',
              icon: Icons.ios_share_rounded,
              variant: AppButtonVariant.outline,
              onPressed: widget.onShare,
            ),
          ],
        ),
      ),
    );
  }

  Widget _legend(
    BuildContext context, {
    required Map<AppRiskLevel, int> counts,
  }) {
    final entries = counts.entries
        .where((e) => e.value > 0)
        .toList(growable: false);
    return Wrap(
      spacing: 14,
      runSpacing: 8,
      children: [
        for (final e in entries)
          Row(
            mainAxisSize: MainAxisSize.min,
            children: [
              Container(
                width: 10,
                height: 10,
                decoration: BoxDecoration(
                  shape: BoxShape.circle,
                  color: e.key.color(context),
                ),
              ),
              const SizedBox(width: 6),
              Text(
                '${e.key.label} (${e.value})',
                style: TextStyle(color: context.textSubtle, fontSize: 12.5),
              ),
            ],
          ),
      ],
    );
  }

  int _computeStreak(List<ApiAnalysisHistoryItem> items) {
    final days = items
        .map((e) => DateUtils.dateOnly(e.createdAt.toLocal()))
        .toSet();
    var streak = 0;
    var day = DateUtils.dateOnly(DateTime.now());
    if (!days.contains(day)) day = day.subtract(const Duration(days: 1));
    while (days.contains(day)) {
      streak++;
      day = day.subtract(const Duration(days: 1));
    }
    return streak;
  }

  Map<AppRiskLevel, int> _countLevels(List<ApiAnalysisHistoryItem> items) {
    final counts = <AppRiskLevel, int>{
      AppRiskLevel.low: 0,
      AppRiskLevel.moderate: 0,
      AppRiskLevel.urgent: 0,
      AppRiskLevel.emergency: 0,
    };
    for (final e in items) {
      counts[appRiskLevelFor(e.triageLevel, e.riskScore)] =
          (counts[appRiskLevelFor(e.triageLevel, e.riskScore)] ?? 0) + 1;
    }
    return counts;
  }
}

