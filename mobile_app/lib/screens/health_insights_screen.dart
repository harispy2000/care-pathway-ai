/// Paints pseudo-3D bars: front face + lit top + shaded side, growing from
/// the baseline as [progress] goes 0→1.
class _Bars3DPainter extends CustomPainter {
  final List<ApiAnalysisHistoryItem> items;
  final double progress;
  final bool dark;
  final Color muted;

  _Bars3DPainter({
    required this.items,
    required this.progress,
    required this.dark,
    required this.muted,
  });

  @override
  void paint(Canvas canvas, Size size) {
    if (items.isEmpty) return;
    const depth = 9.0;
    final baseline = size.height - depth;
    final slot = size.width / items.length;
    final barWidth = math.min(slot * 0.52, 26.0);

    // Baseline.
    final basePaint = Paint()
      ..color = muted.withValues(alpha: 0.8)
      ..strokeWidth = 1;
    canvas.drawLine(
      Offset(0, baseline),
      Offset(size.width, baseline),
      basePaint,
    );

    for (var i = 0; i < items.length; i++) {
      final item = items[i];
      final level = appRiskLevelFor(item.triageLevel, item.riskScore);
      final color = level.baseColor;

      final h = (item.riskScore / 100) * (baseline - 8) * progress;
      final x = slot * i + (slot - barWidth) / 2;
      final y = baseline - h;

      // Front face.
      canvas.drawRRect(
        RRect.fromRectAndCorners(
          Rect.fromLTWH(x, y, barWidth, h),
          topLeft: const Radius.circular(4),
          topRight: const Radius.circular(4),
        ),
        Paint()..color = color.withValues(alpha: 0.85),
      );

      if (h > 2) {
        // Top face (lit).
        final top = Path()
          ..moveTo(x, y)
          ..lineTo(x + barWidth, y)
          ..lineTo(x + barWidth + depth * 0.6, y - depth * 0.6)
          ..lineTo(x + depth * 0.6, y - depth * 0.6)
          ..close();
        canvas.drawPath(
          top,
          Paint()..color = Color.lerp(color, Colors.white, 0.35)!,
        );

        // Side face (shaded).
        final side = Path()
          ..moveTo(x + barWidth, y)
          ..lineTo(x + barWidth + depth * 0.6, y - depth * 0.6)
          ..lineTo(x + barWidth + depth * 0.6, baseline - depth * 0.6)
          ..lineTo(x + barWidth, baseline)
          ..close();
        canvas.drawPath(
          side,
          Paint()..color = Color.lerp(color, Colors.black, 0.28)!,
        );
      }
    }
  }

  @override
  bool shouldRepaint(_Bars3DPainter oldDelegate) =>
      oldDelegate.progress != progress ||
      oldDelegate.items != items ||
      oldDelegate.dark != dark;
}

/// Donut chart with a 3D ring: outer arcs + a subtle drop shadow ring below
/// to fake depth.
class _Donut3DPainter extends CustomPainter {
  final Map<AppRiskLevel, int> counts;
  final double progress;
  final bool dark;

  _Donut3DPainter({
    required this.counts,
    required this.progress,
    required this.dark,
  });

  @override
  void paint(Canvas canvas, Size size) {
    final total = counts.values.fold<int>(0, (a, b) => a + b);
    if (total == 0) return;

    final center = Offset(size.width / 2, size.height / 2);
    final radius = math.min(size.width, size.height) / 2 - 12;
    const stroke = 20.0;

    // Shadow ring for depth.
    canvas.drawCircle(
      center.translate(0, 5),
      radius,
      Paint()
        ..color = Colors.black.withValues(alpha: dark ? 0.35 : 0.10)
        ..style = PaintingStyle.stroke
        ..strokeWidth = stroke
        ..maskFilter = const MaskFilter.blur(BlurStyle.normal, 6),
    );

    const gap = 0.06; // radians between segments
    var start = -math.pi / 2;

    for (final entry in counts.entries) {
      final sweep = (entry.value / total) * 2 * math.pi * progress;
      if (sweep <= gap) {
        start += (entry.value / total) * 2 * math.pi * progress;
        continue;
      }
      final color = entry.key.baseColor;

      final paint = Paint()
        ..style = PaintingStyle.stroke
        ..strokeWidth = stroke
        ..strokeCap = StrokeCap.butt
        ..shader = SweepGradient(
          startAngle: start,
          endAngle: start + sweep,
          colors: [
            Color.lerp(color, Colors.white, 0.25)!,
            color,
          ],
          transform: GradientRotation(start),
        ).createShader(Rect.fromCircle(center: center, radius: radius));

      canvas.drawArc(
        Rect.fromCircle(center: center, radius: radius),
        start + gap / 2,
        sweep - gap,
        false,
        paint,
      );
      start += sweep;
    }
  }

  @override
  bool shouldRepaint(_Donut3DPainter oldDelegate) =>
      oldDelegate.progress != progress || oldDelegate.counts != counts;
}
